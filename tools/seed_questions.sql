Σ (n / 2^(h+1)) · h  → 收敛到 O(n)
```

直观理解：绝大多数节点都在最下面两层，**它们几乎不需要下沉**；只有根附近少数节点需要走满整棵树。而如果改成「逐个插入」建堆，每个元素都要上浮，总数是 `O(n log n)`。

**`std::priority_queue` 的默认行为**：默认是**大顶堆**（`less<int>`）。要小顶堆得写 `priority_queue<int, vector<int>, greater<int>>`，或自己对元素重载 `<` 反向。自定义结构体：

```cpp
struct Task { int prio; };
// 按 prio 小者优先
auto cmp = [](const Task& a, const Task& b) { return a.prio > b.prio; };
std::priority_queue<Task, std::vector<Task>, decltype(cmp)> pq(cmp);
```

**典型应用**：Top K、合并 K 个有序链表、调度器（按优先级出队）、Dijkstra 求最短路、中位数（大小两个堆对顶）。', 2);

